def num_gen(n: int, one: str, many: str) -> str:
    """Число + существительное в родительном падеже: 1 -> «1 рабочего дня», 14 -> «14 рабочих дней»,
    21 -> «21 рабочего дня», 11 -> «11 рабочих дней»."""
    form = one if n % 10 == 1 and n % 100 != 11 else many
    return f"{n} {form}"


