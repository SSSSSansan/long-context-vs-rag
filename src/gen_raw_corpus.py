def _numeric_clause(rng: random.Random, key: str) -> str:
    spec = NUMERIC[key]
    n = rng.randint(spec["lo"], spec["hi"])
    return rng.choice(spec["templates"]).format(v=num_gen(n, *spec["forms"]))


def build_doc(idx: int, topic: str, other: str, unit: str, rng: random.Random, university: str) -> str:
    doc_id = f"doc_{idx:03d}"
    fmt = dict(unit=unit, topic=topic, other=other)

    def pick(bank: list[str]) -> list[str]:
        return [s.format(**fmt) for s in bank if rng.random() < 0.95]

    def numeric(*keys: str) -> list[str]:
        out = [_numeric_clause(rng, k) for k in keys]
        return out

    period = rng.choice(PERIODS)
    period_clause = rng.choice(PERIOD_TEMPLATES).format(p=period)

    sections: list[tuple[str, list[str]]] = []
    intro = (f"Настоящее Положение (далее — Положение) определяет порядок осуществления процедуры «{topic}» "
             f"в {university} (далее — Университет).")
    body = pick(GENERAL)
    rng.shuffle(body)
    sections.append(("Раздел 1. Общие положения", [intro] + body))

    s2 = pick(SUBMIT) + numeric("pages", "attempts")
    rng.shuffle(s2)
    sections.append(("Раздел 2. Порядок подачи заявления", s2))

    s3 = pick(REVIEW) + numeric("review", "committee", "quorum") + [period_clause]
    rng.shuffle(s3)
    sections.append(("Раздел 3. Рассмотрение заявления", s3))

    s4 = pick(DECISION) + numeric("score", "payment", "notify")
    rng.shuffle(s4)
    sections.append(("Раздел 4. Принятие решения и уведомление", s4))

    s5 = pick(APPEAL) + numeric("appeal", "retention")
    rng.shuffle(s5)
    sections.append(("Раздел 5. Обжалование решений и хранение материалов", s5))

    s6 = pick(RIGHTS)
    rng.shuffle(s6)
    sections.append(("Раздел 6. Права и обязанности сторон", s6))

    s7 = pick(FINAL)
    rng.shuffle(s7)
    sections.append(("Раздел 7. Заключительные положения", s7))

    lines = [f"ДОКУМЕНТ {doc_id}",
             f"Положение о порядке проведения процедуры «{topic}»",
             university, ""]
    for si, (title, clauses) in enumerate(sections, start=1):
        lines.append(title)
        for ci, c in enumerate(clauses, start=1):
            lines.append(f"{si}.{ci}. {c}")
        lines.append("")

    items = rng.sample(ANNEX_ITEMS, rng.randint(8, 12))
    lines.append(f"Приложение 1. Перечень документов, прилагаемых к заявлению по процедуре «{topic}»")
    for i, it in enumerate(items, start=1):
        lines.append(f"{i}) {it}{';' if i < len(items) else '.'}")
    lines.append("")
    lines.append(f"Приложение 2. Порядок заполнения заявления по процедуре «{topic}»")
    for i, step in enumerate(FORM_STEPS, start=1):
        lines.append(f"{i}. {step.format(**fmt)}")
    return "\n".join(lines) + "\n"


def generate(out_dir=None) -> list[dict]:
    cfg = load_yaml("configs/corpus.yaml")
    gcfg = cfg["raw_generation"]
    seed = base_cfg()["seed"]
    n = gcfg["n_docs"]
    university = gcfg["university"]
    if n > len(TOPICS):
        raise ValueError(f"n_docs={n} больше числа тем ({len(TOPICS)})")

    out = out_dir or (ROOT / cfg["raw_dir"])
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("doc_*.txt"):
        old.unlink()

    order_rng = random.Random(f"{seed}-topics")
    topics = TOPICS[:]
    order_rng.shuffle(topics)
    topics = topics[:n]

    index = []
    for i, topic in enumerate(topics, start=1):
        rng = random.Random(f"{seed}-doc-{i}")
        other = rng.choice([t for t in topics if t != topic])
        unit = f"«{rng.choice(UNIT_KIND)} {rng.choice(UNIT_AREA)}»"
        text = build_doc(i, topic, other, unit, rng, university)
        (out / f"doc_{i:03d}.txt").write_text(text, encoding="utf-8")
        index.append({"doc_id": f"doc_{i:03d}", "topic": topic, "unit": unit, "chars": len(text)})

    (out / "index.json").write_text(json.dumps(index, ensure_ascii=False, indent=2), encoding="utf-8")
    return index


if __name__ == "__main__":
    idx = generate()
    print(f"Сгенерировано {len(idx)} документов, {sum(d['chars'] for d in idx)} символов.")
